import logging
import sys
import datetime
import os
from agents.researcher import ResearcherAgent
from agents.analyzer import AnalyzerAgent
from agents.intelligence import IntelligenceAgent
from agents.content_creator import ContentCreatorAgent
from agents.health_check import HealthCheckAgent
from agents.monetization import MonetizationAgent
from agents.creativity import CreativityAgent
from agents.advertising import AdvertisingAgent

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger("Orchestrator")

def run_orchestration(save_report=True):
    logger.info(">>> STARTING AUTONOMOUS AGENT SWARM (v2.0 - Evolving) <<<")
    report_data = {}

    # 1. Health Check
    health_agent = HealthCheckAgent()
    health_status = health_agent.run()
    report_data['health'] = health_status

    if health_status.get("site_status") != "healthy":
        logger.error("Target site is unhealthy. Aborting operation.")

    # 2. Research
    research_agent = ResearcherAgent()
    raw_data = research_agent.run({"limit": 2})
    report_data['research'] = {
        'posts_scraped': len(raw_data.get('blog_posts', [])),
        'google_results': len(raw_data.get('google_listings', []))
    }

    if not raw_data.get('blog_posts'):
        logger.warning("No blog data scraped.")

    # 3. Analyze
    analyzer_agent = AnalyzerAgent()
    analysis_result = analyzer_agent.run(raw_data)
    report_data['analysis'] = analysis_result

    # 3.5 Advertising (Collaborating with Analyzer)
    ad_agent = AdvertisingAgent()
    ad_result = ad_agent.run(analysis_result)
    report_data['advertising'] = ad_result

    # 4. Intelligence (Collaborating with Analyzer + Advertising + History)
    intelligence_agent = IntelligenceAgent()
    # Pass combined data for "100% collaboration"
    combined_input = {
        "analysis": analysis_result,
        "advertising": ad_result
    }
    intelligence_result = intelligence_agent.run(combined_input)
    report_data['intelligence'] = intelligence_result

    # 5. Creativity
    creativity_agent = CreativityAgent()
    creative_result = creativity_agent.run(analysis_result)
    report_data['creativity'] = creative_result

    # 6. Monetization
    monetization_agent = MonetizationAgent()
    monetization_result = monetization_agent.run(raw_data.get('blog_posts', []))
    report_data['monetization'] = monetization_result

    # 7. Create Content
    content_agent = ContentCreatorAgent()
    content_draft = content_agent.run(intelligence_result)
    report_data['content_draft'] = content_draft

    logger.info(">>> SWARM OPERATION COMPLETE <<<")

    if save_report:
        save_daily_report(report_data)

    return report_data

def save_daily_report(data):
    today = datetime.datetime.now().strftime("%Y-%m-%d")
    report_dir = "reports"
    os.makedirs(report_dir, exist_ok=True)
    report_file = os.path.join(report_dir, f"daily_report_{today}.md")

    # Helper for status icons
    def get_status_icon(condition):
        return "✅" if condition else "❌"

    with open(report_file, "w", encoding="utf-8") as f:
        # Title
        f.write(f"# 📊 Daily Autonomous Report: {today}\n")
        f.write("*(Generated by Jules Autonomous Swarm with Continuous Learning)*\n\n")

        # Table of Contents
        f.write("## 📋 Table of Contents\n")
        f.write("- [🏥 System Health & Environment](#-system-health--environment)\n")
        f.write("- [🔬 Research Summary](#-research-summary)\n")
        f.write("- [🧠 Strategic Intelligence & Evolution](#-strategic-intelligence--evolution)\n")
        f.write("- [🎯 Advertising & Targeting](#-advertising--targeting)\n")
        f.write("- [💰 Monetization Review](#-monetization-review)\n")
        f.write("- [🎨 Creative Brainstorming](#-creative-brainstorming)\n")
        f.write("- [📝 Automated Content Draft](#-automated-content-draft)\n\n")
        f.write("---\n\n")

        # Health
        f.write("## 🏥 System Health & Environment\n")
        status = data.get('health', {})
        site_healthy = status.get('site_status') == "healthy"

        f.write("| Component | Status | Details |\n")
        f.write("|-----------|--------|---------|\n")
        f.write(
            f"| **Site Status** | {get_status_icon(site_healthy)} | "
            f"{status.get('site_status')} (Code: {status.get('site_code')}) |\n"
        )
        f.write(
            f"| **Robots.txt** | {get_status_icon(status.get('robots_txt_accessible'))} | "
            f"Accessible |\n"
        )
        f.write(
            f"| **Googlebot** | {get_status_icon(status.get('googlebot_allowed'))} | "
            f"Allowed |\n\n"
        )
        f.write("[⬆️ Back to Top](#-table-of-contents)\n\n")

        # Research Stats
        research = data.get('research', {})
        f.write("## 🔬 Research Summary\n")
        f.write(f"- **New Posts Scraped:** `{research.get('posts_scraped')}`\n")
        f.write(f"- **Google Listings Found:** `{research.get('google_results')}`\n\n")
        f.write("[⬆️ Back to Top](#-table-of-contents)\n\n")

        # Intelligence & Evolution
        intel = data.get('intelligence', {})
        f.write("## 🧠 Strategic Intelligence & Evolution\n")
        f.write(f"- **Evolution Status:** {intel.get('evolution_status')}\n")
        f.write(f"- **Recommended Focus:** {intel.get('recommended_focus')}\n")
        f.write("### Insights\n")
        for insight in intel.get('insights', []):
            f.write(f"- 💡 {insight}\n")
        f.write("\n[⬆️ Back to Top](#-table-of-contents)\n\n")

        # Advertising
        ads = data.get('advertising', {})
        f.write("## 🎯 Advertising & Targeting\n")
        f.write(f"**Target Audience:** {ads.get('target_audience')}\n\n")

        f.write("<details>\n<summary><strong>View Bid Strategy</strong></summary>\n\n")
        f.write("| Keyword | Bid | Strategy |\n")
        f.write("|---------|-----|----------|\n")
        for bid in ads.get('bid_strategy', []):
            f.write(f"| {bid['keyword']} | {bid['suggested_bid']} | {bid['strategy']} |\n")
        f.write("\n</details>\n\n")
        f.write("[⬆️ Back to Top](#-table-of-contents)\n\n")

        # Monetization
        money = data.get('monetization', {})
        f.write("## 💰 Monetization Review\n")
        f.write(f"**Summary:** {money.get('summary')}\n\n")
        for detail in money.get('details', []):
            f.write(f"- 💵 {detail}\n")
        f.write("\n[⬆️ Back to Top](#-table-of-contents)\n\n")

        # Creativity
        creative = data.get('creativity', {})
        f.write("## 🎨 Creative Brainstorming\n")
        for idea in creative.get('creative_ideas', []):
            f.write(f"- ✨ {idea}\n")
        f.write("\n[⬆️ Back to Top](#-table-of-contents)\n\n")

        # Content Draft
        draft = data.get('content_draft', {})
        f.write("## 📝 Automated Content Draft\n")
        f.write(f"### {draft.get('draft_title', 'Untitled')}\n\n")
        f.write(draft.get('draft_content', ''))
        f.write("\n\n[⬆️ Back to Top](#-table-of-contents)\n")

    logger.info(f"Report saved to {report_file}")

if __name__ == "__main__":
    run_orchestration()
