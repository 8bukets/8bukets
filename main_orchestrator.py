import logging
import sys
import datetime
import os
from agents.researcher import ResearcherAgent
from agents.analyzer import AnalyzerAgent
from agents.intelligence import IntelligenceAgent
from agents.content_creator import ContentCreatorAgent
from agents.health_check import HealthCheckAgent
from agents.monetization import MonetizationAgent
from agents.creativity import CreativityAgent
from agents.advertising import AdvertisingAgent

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(name)s - %(levelname)s - %(message)s'
)
logger = logging.getLogger("Orchestrator")

# ANSI Colors for CLI UX
class Colors:
    HEADER = '\033[95m'
    BLUE = '\033[94m'
    CYAN = '\033[96m'
    GREEN = '\033[92m'
    WARNING = '\033[93m'
    FAIL = '\033[91m'
    ENDC = '\033[0m'
    BOLD = '\033[1m'
    UNDERLINE = '\033[4m'

def print_header(text):
    print(f"\n{Colors.HEADER}{Colors.BOLD}{'=' * 60}{Colors.ENDC}")
    print(f"{Colors.HEADER}{Colors.BOLD} {text.center(58)} {Colors.ENDC}")
    print(f"{Colors.HEADER}{Colors.BOLD}{'=' * 60}{Colors.ENDC}\n")

def run_orchestration(save_report=True):
    print_header("STARTING AUTONOMOUS AGENT SWARM (v2.0)")
    logger.info("Initializing agents...")
    report_data = {}

    # 1. Health Check
    health_agent = HealthCheckAgent()
    health_status = health_agent.run() or {}
    report_data['health'] = health_status

    if health_status.get("site_status") != "healthy":
        logger.error(f"{Colors.FAIL}Target site is unhealthy. Aborting operation.{Colors.ENDC}")
        # Continue anyway for demo purposes, or return? Original code didn't return.
        # But if unhealthy, scraping might fail.
    else:
        logger.info(f"{Colors.GREEN}System Health Check Passed{Colors.ENDC}")

    # 2. Research
    research_agent = ResearcherAgent()
    raw_data = research_agent.run({"limit": 2}) or {}
    report_data['research'] = {
        'posts_scraped': len(raw_data.get('blog_posts', [])),
        'google_results': len(raw_data.get('google_listings', []))
    }

    if not raw_data.get('blog_posts'):
        logger.warning(f"{Colors.WARNING}No blog data scraped.{Colors.ENDC}")

    # 3. Analyze
    analyzer_agent = AnalyzerAgent()
    analysis_result = analyzer_agent.run(raw_data) or {}
    report_data['analysis'] = analysis_result

    # 3.5 Advertising (Collaborating with Analyzer)
    ad_agent = AdvertisingAgent()
    ad_result = ad_agent.run(analysis_result) or {}
    report_data['advertising'] = ad_result

    # 4. Intelligence (Collaborating with Analyzer + Advertising + History)
    intelligence_agent = IntelligenceAgent()
    # Pass combined data for "100% collaboration"
    combined_input = {
        "analysis": analysis_result,
        "advertising": ad_result
    }
    intelligence_result = intelligence_agent.run(combined_input) or {}
    report_data['intelligence'] = intelligence_result

    # 5. Creativity
    creativity_agent = CreativityAgent()
    creative_result = creativity_agent.run(analysis_result) or {}
    report_data['creativity'] = creative_result

    # 6. Monetization
    monetization_agent = MonetizationAgent()
    monetization_result = monetization_agent.run(raw_data.get('blog_posts', [])) or {}
    report_data['monetization'] = monetization_result

    # 7. Create Content
    content_agent = ContentCreatorAgent()
    content_draft = content_agent.run(intelligence_result) or {}
    report_data['content_draft'] = content_draft

    print_header("SWARM OPERATION COMPLETE")
    logger.info("Generating report...")

    if save_report:
        save_daily_report(report_data)

    return report_data

def save_daily_report(data):
    today = datetime.datetime.now().strftime("%Y-%m-%d")
    report_dir = "reports"
    os.makedirs(report_dir, exist_ok=True)
    report_file = os.path.join(report_dir, f"daily_report_{today}.md")

    with open(report_file, "w", encoding="utf-8") as f:
        f.write(f"# <a name='top'></a>🎨 Daily Autonomous Report: {today}\n")
        f.write("*(Generated by Jules Autonomous Swarm with Continuous Learning)*\n\n")

        # Table of Contents
        f.write("## 📋 Table of Contents\n")
        f.write("1. [System Health & Environment](#system-health)\n")
        f.write("2. [Research Summary](#research-summary)\n")
        f.write("3. [Strategic Intelligence & Evolution](#strategic-intelligence)\n")
        f.write("4. [Advertising & Targeting](#advertising)\n")
        f.write("5. [Monetization Review](#monetization)\n")
        f.write("6. [Creative Brainstorming](#creativity)\n")
        f.write("7. [Automated Content Draft](#content-draft)\n\n")
        f.write("---\n\n")

        # Health
        f.write("## <a name='system-health'></a>1. System Health & Environment\n")
        status = data.get('health') or {}
        site_status = status.get('site_status', 'Unknown')
        icon = "✅" if site_status == "healthy" else "❌"
        f.write(f"- **Site Status:** {icon} {site_status} (Code: {status.get('site_code', 'N/A')})\n")
        f.write(f"- **Robots.txt Access:** {status.get('robots_txt_accessible', 'Unknown')}\n")
        f.write(f"- **Googlebot Allowed:** {status.get('googlebot_allowed', 'Unknown')}\n")
        f.write("\n[Back to Top](#top)\n\n")

        # Research Stats
        research = data.get('research') or {}
        f.write("## <a name='research-summary'></a>2. Research Summary\n")
        f.write(f"- **New Posts Scraped:** {research.get('posts_scraped', 0)}\n")
        f.write(f"- **Google Listings Found:** {research.get('google_results', 0)}\n")
        f.write("\n[Back to Top](#top)\n\n")

        # Intelligence & Evolution
        intel = data.get('intelligence') or {}
        f.write("## <a name='strategic-intelligence'></a>3. Strategic Intelligence & Evolution\n")
        f.write(f"- **Evolution Status:** {intel.get('evolution_status', 'Pending')}\n")
        f.write(f"- **Recommended Focus:** {intel.get('recommended_focus', 'None')}\n")
        for insight in intel.get('insights', []):
            f.write(f"- {insight}\n")
        if not intel.get('insights'):
             f.write("- *No insights available*\n")
        f.write("\n[Back to Top](#top)\n\n")

        # Advertising
        ads = data.get('advertising') or {}
        f.write("## <a name='advertising'></a>4. Advertising & Targeting (Google Antigravity Colab)\n")
        f.write(f"- **Target Audience:** {ads.get('target_audience', 'Pending')}\n")
        f.write("- **Bid Strategy:**\n")
        if ads.get('bid_strategy'):
            for bid in ads.get('bid_strategy', []):
                f.write(f"  - **{bid.get('keyword')}**: {bid.get('suggested_bid')} ({bid.get('strategy')})\n")
        else:
            f.write("  - *No bid strategy generated*\n")
        f.write("\n[Back to Top](#top)\n\n")

        # Monetization
        money = data.get('monetization') or {}
        f.write("## <a name='monetization'></a>5. Monetization Review\n")
        f.write(f"- **Summary:** {money.get('summary', 'Pending')}\n")
        for detail in money.get('details', []):
            f.write(f"- {detail}\n")
        if not money.get('details'):
             f.write("- *No details available*\n")
        f.write("\n[Back to Top](#top)\n\n")

        # Creativity
        creative = data.get('creativity') or {}
        f.write("## <a name='creativity'></a>6. Creative Brainstorming\n")
        for idea in creative.get('creative_ideas', []):
            f.write(f"- {idea}\n")
        if not creative.get('creative_ideas'):
             f.write("- *No creative ideas generated*\n")
        f.write("\n[Back to Top](#top)\n\n")

        # Content Draft
        draft = data.get('content_draft') or {}
        f.write("## <a name='content-draft'></a>7. Automated Content Draft\n")
        f.write(f"### {draft.get('draft_title', 'Untitled')}\n\n")
        f.write(draft.get('draft_content', '*Content generation pending*'))
        f.write("\n\n[Back to Top](#top)\n")

    logger.info(f"{Colors.GREEN}Report saved to {report_file}{Colors.ENDC}")

if __name__ == "__main__":
    run_orchestration()
